"""End-to-end tests for the benchmark command, driven through ``app.bench.__main__.main``.

The adapters under ``app/tests/bench_adapters`` are deliberately stupid: one returns a fixed
sentence, one always fails, one reaches for the network. They exist to prove the harness records
what happened. **No number produced here is evidence about recognition quality, and these tests
establish no statistical rate.**
"""

from __future__ import annotations

import json
import os
import pathlib
import struct
import tempfile
import unittest
import wave
from unittest import mock

from app.bench import (EXIT_INVALID_RESULT, EXIT_MISSING_ADAPTER, EXIT_NETWORK_VIOLATION, EXIT_OK,
                       EXIT_RUN_FAILED, EXIT_USAGE)
from app.bench.__main__ import main
from app.bench import results as results_module

REPO = pathlib.Path(__file__).resolve().parents[2]
ADAPTERS = REPO / "app" / "tests" / "bench_adapters"
ASR = str(ADAPTERS / "asr_fixed.py")
TTS = str(ADAPTERS / "tts_signal.py")
TURN = str(ADAPTERS / "turn_canned.py")


def write_wav(path: pathlib.Path, seconds: float = 0.2, rate: int = 16000) -> pathlib.Path:
    frames = b"".join(struct.pack("<h", 1200 if index % 2 else -1200)
                      for index in range(int(seconds * rate)))
    with wave.open(str(path), "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(rate)
        handle.writeframes(frames)
    return path


def write_pack(directory: pathlib.Path, items: list[dict]) -> pathlib.Path:
    """A tiny licensed pack: generated tones with declared transcripts, no personal audio."""
    directory.mkdir(parents=True, exist_ok=True)
    payload = []
    for item in items:
        write_wav(directory / f"{item['id']}.wav")
        payload.append({"id": item["id"], "file": f"{item['id']}.wav",
                        "language": item["language"], "transcript": item["transcript"],
                        "entities": item.get("entities", []), "licence": "CC0-1.0",
                        "source": "tone generated by the test suite", "condition": "clean"})
    (directory / "pack.json").write_text(
        json.dumps({"schema": "jarvis.voice-fixtures/1", "items": payload}), encoding="utf-8")
    return directory


class BenchmarkRunTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.root = pathlib.Path(self._tmp.name)

    def out(self, name="run"):
        return str(self.root / name)

    def run_main(self, *arguments):
        return main(list(arguments))

    def read_result(self, name="run"):
        path = self.root / name / "result.json"
        self.assertTrue(path.is_file(), path)
        return json.loads(path.read_text(encoding="utf-8"))

    # ------------------------------------------------------------------ happy path
    def test_a_small_run_produces_a_valid_result_and_a_report(self):
        exit_code = self.run_main("--asr-adapter", ASR, "--tts-adapter", TTS,
                                  "--repeat", "1", "--warmup", "0", "--out", self.out())
        self.assertEqual(exit_code, EXIT_OK)
        document = self.read_result()
        self.assertEqual(results_module.validate_result(document), [])
        self.assertEqual(document["run"]["status"], "completed")
        self.assertGreater(document["run"]["samples"], 0)
        self.assertTrue((self.root / "run" / "report.md").is_file())
        self.assertTrue((self.root / "run" / "plan.json").is_file())
        self.assertTrue((self.root / "run" / "fixtures").is_dir())

    def test_synthetic_audio_never_yields_a_word_error_rate(self):
        self.run_main("--asr-adapter", ASR, "--repeat", "2", "--warmup", "0", "--out", self.out())
        document = self.read_result()
        self.assertIn("no speech", document["not_measured"]["wer"])
        self.assertIsNone(document["overall"]["by_phase"]["asr"]["latency_all"]["p50_ms"])
        self.assertEqual(
            document["overall"]["by_phase"]["asr"]["latency_all"]["not_measured"],
            "insufficient_samples")

    def test_a_development_host_is_flagged_everywhere(self):
        self.run_main("--asr-adapter", ASR, "--repeat", "1", "--warmup", "0", "--out", self.out())
        document = self.read_result()
        self.assertEqual(document["host_role_source"], "operator_declaration")
        self.assertFalse(document["decision_eligible"])
        self.assertFalse(document["comparable_to_owner_server"])
        report = (self.root / "run" / "report.md").read_text(encoding="utf-8")
        self.assertIn("development host", report)
        self.assertIn("not a capability", report)

    def test_warm_up_items_are_discarded_before_measurement(self):
        self.run_main("--asr-adapter", ASR, "--repeat", "2", "--warmup", "1", "--out", self.out())
        document = self.read_result()
        plan = json.loads((self.root / "run" / "plan.json").read_text(encoding="utf-8"))
        measured_tasks = plan["task_count"] - 9  # one warm-up round of nine fixtures
        self.assertEqual(document["run"]["samples"], measured_tasks)
        self.assertEqual({sample["repeat"] for sample in document["items"]}, {0, 1})

    def test_the_result_contains_no_personal_path_and_no_secret(self):
        self.run_main("--asr-adapter", ASR, "--repeat", "1", "--warmup", "0", "--out", self.out())
        text = (self.root / "run" / "result.json").read_text(encoding="utf-8")
        self.assertNotIn("/home/", text)
        self.assertIn("<repo>/app/tests/bench_adapters", text)  # paths are published as tokens
        self.assertNotIn("jvs_", text)
        self.assertNotIn(os.environ.get("USER", "\0"), text.replace("<repo>", ""))

    def test_the_same_configuration_produces_the_same_plan_hash(self):
        for name in ("first", "second"):
            self.run_main("--asr-adapter", ASR, "--repeat", "1", "--warmup", "0",
                          "--out", self.out(name))
        first = self.read_result("first")
        second = self.read_result("second")
        self.assertEqual(first["identity"]["plan_hash"], second["identity"]["plan_hash"])
        self.assertEqual(first["adapters"]["declared"], second["adapters"]["declared"])
        # The measurement itself is not claimed to be reproducible to the microsecond.
        self.assertIn("p50_ms", json.dumps(first["overall"]["by_phase"]).replace("null", ""))

    # ------------------------------------------------------------------ per language
    def test_each_language_is_measured_from_its_own_fixtures_only(self):
        pack = write_pack(self.root / "pack", [
            {"id": "en_one", "language": "en", "transcript": "Lights on.",
             "entities": [{"kind": "device", "text": "lights"}]},
            {"id": "hi_one", "language": "hi", "transcript": "Batti jalao.",
             "entities": [{"kind": "device", "text": "batti"}]},
        ])
        with mock.patch.dict(os.environ, {"BENCH_TEST_TEXT": "Lights on."}, clear=False):
            exit_code = self.run_main("--asr-adapter", ASR, "--fixtures", str(pack),
                                      "--languages", "en,hi", "--repeat", "25", "--warmup", "0",
                                      "--out", self.out())
        self.assertEqual(exit_code, EXIT_OK)
        document = self.read_result()
        entries = {entry["code"]: entry for entry in document["languages"]}
        self.assertEqual(entries["en"]["status"], "measured")
        self.assertEqual(entries["hi"]["status"], "measured")
        # The fixed-output adapter says the English sentence, so Hindi must fail: a result is never
        # carried from one language to an alphabet neighbour.
        self.assertAlmostEqual(entries["en"]["wer"]["mean"], 0.0, places=6)
        self.assertAlmostEqual(entries["hi"]["wer"]["mean"], 1.0, places=6)
        self.assertEqual(entries["en"]["task_success"]["value"], 1.0)
        self.assertEqual(entries["hi"]["task_success"]["value"], 0.0)
        self.assertEqual(entries["en"]["tier"], "not_assigned")
        self.assertIsNone(entries["en"]["fluency_claim"])
        # Languages nobody scheduled stay empty.
        self.assertEqual(entries["es"]["status"], "not_run")
        self.assertIn("everything", entries["es"]["not_measured"])

    def test_below_the_sample_gate_a_language_is_not_reported(self):
        pack = write_pack(self.root / "pack", [
            {"id": "en_one", "language": "en", "transcript": "Lights on."}])
        with mock.patch.dict(os.environ, {"BENCH_TEST_TEXT": "Lights on."}, clear=False):
            exit_code = self.run_main("--asr-adapter", ASR, "--fixtures", str(pack),
                                      "--languages", "en", "--repeat", "3", "--warmup", "0",
                                      "--out", self.out())
        self.assertEqual(exit_code, EXIT_OK)
        document = self.read_result()
        english = next(entry for entry in document["languages"] if entry["code"] == "en")
        self.assertEqual(english["status"], "not_measured")
        self.assertIsNone(english["wer"])
        self.assertIn("wer", english["below_gate"])
        self.assertFalse(english["below_gate"]["wer"]["gate_cleared"])
        self.assertEqual(document["not_measured"]["wer"],
                         "recognition samples exist per language but fewer than 20 items per "
                         "language cleared the WER sample gate; the point estimates are kept under "
                         "below_gate and must not be quoted as a result")

    def test_an_unscheduled_language_is_never_run_even_when_audio_exists(self):
        pack = write_pack(self.root / "pack", [
            {"id": "en_one", "language": "en", "transcript": "Lights on."},
            {"id": "hi_one", "language": "hi", "transcript": "Batti jalao."}])
        self.run_main("--asr-adapter", ASR, "--fixtures", str(pack), "--languages", "en",
                      "--repeat", "2", "--warmup", "0", "--out", self.out())
        document = self.read_result()
        hindi = next(entry for entry in document["languages"] if entry["code"] == "hi")
        self.assertEqual(hindi["status"], "not_run")
        self.assertIsNone(hindi["wer"])
        self.assertFalse(any(sample.get("language") == "hi" for sample in document["items"]))

    # ------------------------------------------------------------------ refusals
    def test_no_adapter_means_a_dedicated_exit_code_and_no_run(self):
        exit_code = self.run_main("--out", self.out())
        self.assertEqual(exit_code, EXIT_MISSING_ADAPTER)
        self.assertFalse((self.root / "run" / "result.json").exists())

    def test_an_unknown_language_is_refused(self):
        exit_code = self.run_main("--asr-adapter", ASR, "--languages", "xx", "--out", self.out())
        self.assertEqual(exit_code, EXIT_USAGE)

    def test_a_path_that_does_not_exist_is_refused_before_measuring(self):
        exit_code = self.run_main("--asr-adapter", str(self.root / "nope.py"), "--out", self.out())
        self.assertEqual(exit_code, EXIT_MISSING_ADAPTER)
        self.assertFalse((self.root / "run" / "result.json").exists())

    def test_a_hash_mismatch_is_fatal(self):
        exit_code = self.run_main("--asr-adapter", ASR, "--asr-model", ASR,
                                  "--asr-model-sha256", "0" * 64, "--out", self.out())
        self.assertEqual(exit_code, EXIT_USAGE)
        self.assertFalse((self.root / "run" / "result.json").exists())

    def test_plan_only_writes_a_plan_and_runs_nothing(self):
        exit_code = self.run_main("--plan-only", "--asr-adapter", ASR, "--languages", "en",
                                  "--out", self.out())
        self.assertEqual(exit_code, EXIT_OK)
        self.assertTrue((self.root / "run" / "plan.json").is_file())
        self.assertFalse((self.root / "run" / "result.json").exists())

    def test_an_out_of_range_repeat_count_is_refused(self):
        self.assertEqual(self.run_main("--asr-adapter", ASR, "--repeat", "0", "--out", self.out()),
                         EXIT_USAGE)

    # ------------------------------------------------------------------ local only
    def test_a_request_time_network_attempt_ends_the_run(self):
        exit_code = self.run_main("--asr-adapter", str(ADAPTERS / "asr_network.py"),
                                  "--repeat", "1", "--warmup", "0", "--out", self.out())
        self.assertEqual(exit_code, EXIT_NETWORK_VIOLATION)
        document = self.read_result()
        self.assertEqual(document["run"]["status"], "violated")
        self.assertEqual(document["decision"]["decision"], "rejected")
        self.assertTrue(document["network"]["violations"])
        self.assertFalse(document["decision_eligible"])
        self.assertTrue(document["network"]["denied"])

    def test_an_import_time_network_attempt_is_caught_too(self):
        exit_code = self.run_main("--asr-adapter", str(ADAPTERS / "asr_import_network.py"),
                                  "--repeat", "1", "--warmup", "0", "--out", self.out())
        self.assertEqual(exit_code, EXIT_NETWORK_VIOLATION)
        document = self.read_result()
        self.assertEqual(document["run"]["status"], "violated")
        self.assertEqual(document["decision"]["decision"], "rejected")

    def test_the_sandbox_is_deny_by_default(self):
        self.run_main("--asr-adapter", ASR, "--repeat", "1", "--warmup", "0", "--out", self.out())
        network = self.read_result()["network"]
        self.assertTrue(network["denied"])
        self.assertFalse(network["loopback_allowed"])
        self.assertEqual(network["attempts"], 0)

    # ------------------------------------------------------------------ failure handling
    def test_an_adapter_that_always_fails_is_recorded_as_failure_not_as_zero(self):
        exit_code = self.run_main("--asr-adapter", str(ADAPTERS / "asr_broken.py"),
                                  "--repeat", "1", "--warmup", "0", "--out", self.out())
        self.assertEqual(exit_code, EXIT_RUN_FAILED)
        document = self.read_result()
        self.assertEqual(document["run"]["status"], "failed")
        self.assertEqual(document["run"]["samples"], 0)
        self.assertTrue(document["failures"])
        for failure in document["failures"]:
            self.assertTrue(failure["task_id"])
            self.assertTrue(failure["code"])
        self.assertEqual(document["decision"]["decision"], "not_decidable")
        self.assertIsNotNone(document["not_measured"]["latency_p50"])

    def test_a_failure_never_produces_a_measured_language(self):
        pack = write_pack(self.root / "pack", [
            {"id": "en_one", "language": "en", "transcript": "Lights on."}])
        exit_code = self.run_main("--asr-adapter", str(ADAPTERS / "asr_broken.py"),
                                  "--fixtures", str(pack), "--languages", "en",
                                  "--repeat", "2", "--warmup", "0", "--out", self.out())
        self.assertEqual(exit_code, EXIT_RUN_FAILED)
        document = self.read_result()
        english = next(entry for entry in document["languages"] if entry["code"] == "en")
        self.assertEqual(english["status"], "not_measured")
        self.assertIsNone(english["wer"])

    # ------------------------------------------------------------------ criteria
    def test_a_criteria_file_on_a_development_host_is_not_decidable(self):
        criteria = self.root / "criteria.json"
        criteria.write_text(json.dumps({
            "schema": "jarvis.voice-bench-criteria/1", "criteria_id": "test-bar",
            "min_samples_per_language": 1, "languages_required": [],
            "thresholds": {"wer_mean_max": 0.9}}), encoding="utf-8")
        self.run_main("--asr-adapter", ASR, "--repeat", "2", "--warmup", "0",
                      "--criteria", str(criteria), "--out", self.out())
        document = self.read_result()
        self.assertEqual(document["decision"]["decision"], "not_decidable")
        self.assertIn("development host", " ".join(document["decision"]["reasons"]))
        self.assertEqual(document["decision"]["gate_status"]["G-O1"], "blocked")
        self.assertEqual(document["decision"]["criteria"]["criteria_id"], "test-bar")

    def test_a_criteria_file_that_names_a_product_is_refused(self):
        criteria = self.root / "criteria.json"
        criteria.write_text(json.dumps({
            "schema": "jarvis.voice-bench-criteria/1", "criteria_id": "test-bar",
            "thresholds": {"wer_mean_max": 0.9}, "winner": "this one"}), encoding="utf-8")
        exit_code = self.run_main("--asr-adapter", ASR, "--repeat", "1", "--warmup", "0",
                                  "--criteria", str(criteria), "--out", self.out())
        self.assertEqual(exit_code, EXIT_USAGE)
        document = self.read_result()
        self.assertEqual(document["decision"]["decision"], "not_decidable")
        self.assertTrue(document["decision"]["criteria"]["error"])


class InvalidResultTests(unittest.TestCase):
    def test_an_invalid_document_is_reported_with_a_dedicated_exit_code(self):
        with tempfile.TemporaryDirectory() as directory:
            target = pathlib.Path(directory) / "result.json"
            with self.assertRaises(results_module.ResultError):
                results_module.write_result({"schema": "nope"}, target)
            self.assertFalse(target.exists())
        self.assertEqual(EXIT_INVALID_RESULT, 3)


